export function translate(locale: Locale, message: string, params?: TranslationParams) {
  const template = locale === 'vi' ? viMessages[message] ?? message : message;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => String(params[key] ?? match));
}

const apiLabelMessages: Record<string, string> = {
  'Display name': 'Tên hiển thị',
  'Invite code': 'Mã lời mời',
  'Conversation name': 'Tên cuộc trò chuyện',
  Content: 'Nội dung',
  'Color A': 'Màu A',
  'Color B': 'Màu B',
};

/** Translate API messages whose useful values are generated at runtime. */
export function translateApiMessage(locale: Locale, message: string) {
  const exact = translate(locale, message);
  if (locale !== 'vi' || exact !== message) return exact;

  const textRange = message.match(/^(.+) must be between (\d+) and (\d+) characters\.$/);
  if (textRange) {
    const [, label, min, max] = textRange;
    return `${apiLabelMessages[label] ?? label} phải có từ ${min} đến ${max} ký tự.`;
  }

  const rateLimit = message.match(/^Actions are being sent too quickly\. Try again in (\d+) seconds\.$/);
  if (rateLimit) return `Bạn thao tác quá nhanh. Hãy thử lại sau ${rateLimit[1]} giây.`;

  const paletteLimit = message.match(/^A palette can store up to (\d+) colors\.$/);
  if (paletteLimit) return `Một bảng màu có thể lưu tối đa ${paletteLimit[1]} màu.`;

  const hexColor = message.match(/^(.+) must be a 6-digit HEX color\.$/);
  if (hexColor) {
    const label = apiLabelMessages[hexColor[1]] ?? hexColor[1].replace(/^Color (\d+)$/, 'Màu $1');
    return `${label} phải là mã màu HEX gồm 6 chữ số.`;
  }

  const formulaRange = message.match(/^A formula needs (\d+) to (\d+) component colors\.$/);
  if (formulaRange) return `Một công thức cần từ ${formulaRange[1]} đến ${formulaRange[2]} màu thành phần.`;

  const invalidColor = message.match(/^Color (\d+) is invalid\.$/);
  if (invalidColor) return `Màu ${invalidColor[1]} không hợp lệ.`;

  const invalidParts = message.match(/^Parts for color (\d+) must be between (\d+) and (\d+)\.$/);
  if (invalidParts) return `Số phần của màu ${invalidParts[1]} phải nằm trong khoảng từ ${invalidParts[2]} đến ${invalidParts[3]}.`;

  return message;
}

export function localeTag(locale: Locale) {
  return locale === 'vi' ? 'vi-VN' : 'en-US';
}

export function hasVietnameseTranslation(message: string) {
  return Object.prototype.hasOwnProperty.call(viMessages, message);
}
